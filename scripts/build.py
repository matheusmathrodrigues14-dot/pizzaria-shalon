"""Generate a self-contained index.html for isolated previews and static hosting."""

from __future__ import annotations

import base64
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "source" / "index.html"
OUTPUT = ROOT / "index.html"

CSS_LINK = '<link rel="stylesheet" href="./styles.css" />'
JS_LINK = '<script src="./script.js" defer></script>'
LIBRARIES = (
    ('<script src="./vendor/gsap.min.js" defer></script>', "gsap.min.js"),
    ('<script src="./vendor/ScrollTrigger.min.js" defer></script>', "ScrollTrigger.min.js"),
    ('<script src="./vendor/lenis.min.js" defer></script>', "lenis.min.js"),
)
PRELOAD = '<link rel="preload" as="image" href="./public/assets/pizza-salgada-destaque.webp" />'
ASSET_PATH = re.compile(r"\./public/assets/[A-Za-z0-9_./-]+")
MEDIA_TYPES = {".webp": "image/webp", ".svg": "image/svg+xml", ".woff2": "font/woff2"}


def main() -> None:
    html = SOURCE.read_text(encoding="utf-8")
    css = (ROOT / "styles.css").read_text(encoding="utf-8")
    js = (ROOT / "script.js").read_text(encoding="utf-8")

    for marker in (CSS_LINK, JS_LINK, PRELOAD, *(tag for tag, _ in LIBRARIES)):
        if html.count(marker) != 1:
            raise ValueError(f"Expected one occurrence of {marker!r}")

    html = html.replace(PRELOAD, "")
    html = html.replace(CSS_LINK, f"<style>\n{css}\n</style>")
    inline_scripts = []
    for tag, filename in LIBRARIES:
        library = (ROOT / "vendor" / filename).read_text(encoding="utf-8")
        if "</script" in library.lower():
            raise ValueError(f"Script closing tag found in {filename}")
        inline_scripts.append(f"<script>\n{library}\n</script>")
        html = html.replace(tag, "")
    html = html.replace(JS_LINK, "")
    if html.count("</body>") != 1:
        raise ValueError("Expected a single closing body tag")
    inline_scripts.append(f"<script>\n{js}\n</script>")
    html = html.replace("</body>", "\n".join(inline_scripts) + "\n</body>")

    cache: dict[str, str] = {}

    def embed(match: re.Match[str]) -> str:
        relative = match.group(0).removeprefix("./")
        if relative not in cache:
            path = (ROOT / relative).resolve()
            if not path.is_relative_to(ROOT / "public" / "assets") or not path.is_file():
                raise FileNotFoundError(f"Missing or invalid asset: {relative}")
            media_type = MEDIA_TYPES.get(path.suffix)
            if media_type is None:
                raise ValueError(f"Unsupported asset type: {relative}")
            encoded = base64.b64encode(path.read_bytes()).decode("ascii")
            cache[relative] = f"data:{media_type};base64,{encoded}"
        return cache[relative]

    html = ASSET_PATH.sub(embed, html)
    if "./public/assets/" in html or CSS_LINK in html or JS_LINK in html or any(tag in html for tag, _ in LIBRARIES):
        raise ValueError("Unbundled resource remains in generated HTML")
    html = re.sub(r"(?m)[ \t]+$", "", html)

    OUTPUT.write_text(
        "<!-- Generated by scripts/build.py from source/index.html, styles.css, script.js and vendor/. -->\n" + html,
        encoding="utf-8",
    )
    print(f"Built {OUTPUT.name} with {len(cache)} local assets ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
